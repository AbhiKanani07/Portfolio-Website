// Bundles src/ into docs/assets (GitHub Pages serves docs/), regenerates the
// knowledge JSON for the optional endpoint, and with --single writes one
// self-contained HTML file to dist/.
import { build, transform } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => path.join(root, ...p);

async function bundle() {
  await build({
    entryPoints: [r('src/main.js')], bundle: true, minify: true, format: 'esm', target: ['es2020'],
    outfile: r('docs/assets/site.js'), legalComments: 'none', logLevel: 'warning',
  });
  const css = (await Promise.all(['tokens', 'base', 'components'].map((n) => readFile(r(`src/styles/${n}.css`), 'utf8')))).join('\n');
  const out = await transform(css, { loader: 'css', minify: true, target: ['chrome111', 'safari16.4', 'firefox115'] });
  await writeFile(r('docs/assets/site.css'), out.code);
  const { KB } = await import(`${pathToFileURL(r('src/ai/knowledge.js')).href}?v=${Date.now()}`);
  const json = JSON.stringify(KB, null, 2);
  await writeFile(r('docs/knowledge.json'), `${json}\n`);
  await mkdir(r('api'), { recursive: true });
  const { buildSystemPrompt } = await import(`${pathToFileURL(r('src/ai/prompt.js')).href}?v=${Date.now()}`);
  await writeFile(r('api/knowledge.js'), `// Generated by tools/build.mjs from src/ai/knowledge.js. Edit that file, not this one.\nexport const KB = ${json};\nexport const SYSTEM = ${JSON.stringify(buildSystemPrompt(KB))};\n`);
}

async function single() {
  let html = await readFile(r('docs/index.html'), 'utf8');
  const css = await readFile(r('docs/assets/site.css'), 'utf8');
  const js = (await readFile(r('docs/assets/site.js'), 'utf8')).replace(/<\/script/gi, '<\\/script');
  const b64 = async (p) => (await readFile(p)).toString('base64');
  const jpg = await b64(r('docs/assets/img/abhi-kanani-480.jpg'));
  const fav = await b64(r('docs/assets/favicon.svg'));
  html = html.replace('<link rel="stylesheet" href="assets/site.css">', () => `<style>${css}</style>`);
  html = html.replace('<script type="module" src="assets/site.js"></script>', () => `<script type="module">${js}</script>`);
  html = html.replace(/<source type="image\/webp"[^>]*>\s*/, '');
  html = html.replace(/<img src="assets\/img\/abhi-kanani-480\.jpg" srcset="[^"]*"/, () => `<img src="data:image/jpeg;base64,${jpg}"`);
  html = html.replace('href="assets/favicon.svg"', () => `href="data:image/svg+xml;base64,${fav}"`);
  html = html.replace(/\s*<link rel="apple-touch-icon"[^>]*>/, '');
  await mkdir(r('dist'), { recursive: true });
  await writeFile(r('dist/abhi-kanani-portfolio.html'), html);
}

await bundle();
if (process.argv.includes('--single')) await single();
console.log('built docs/assets/site.js, docs/assets/site.css, docs/knowledge.json, api/knowledge.js' + (process.argv.includes('--single') ? ', dist/abhi-kanani-portfolio.html' : ''));
